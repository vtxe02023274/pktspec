import {
  PRIMITIVE_SIZES,
  findEnum,
  wireSize,
  type ElementType,
  type Field,
  type Packet,
  type PrimitiveType,
  type Protocol,
} from '../model.js';
import { hex, uniqueName, type GeneratedFile } from './common.js';

export interface WiresharkOptions {
  /** Default for the TCP, UDP and server port preferences; none when omitted. */
  port?: number | undefined;
}

const FIELD_CONSTRUCTORS: Record<PrimitiveType, string> = {
  u8: 'uint8',
  u16: 'uint16',
  u32: 'uint32',
  u64: 'uint64',
  i8: 'int8',
  i16: 'int16',
  i32: 'int32',
  i64: 'int64',
  f32: 'float',
  f64: 'double',
  bool: 'bool',
};

const LENGTH_CONSTRUCTORS = { 1: 'uint8', 2: 'uint16', 4: 'uint32' } as const;

export function generateWireshark(
  protocol: Protocol,
  options: WiresharkOptions = {},
): GeneratedFile[] {
  const port = options.port ?? 0;
  if (!Number.isInteger(port) || port < 0 || port > 65535) {
    throw new Error(`'${port}' is not a valid port; expected an integer from 1 to 65535`);
  }
  return [{ path: `${protocol.name}.lua`, content: new WiresharkGenerator(protocol, port).file() }];
}

class WiresharkGenerator {
  private readonly prefix: string;
  private readonly used = new Set<string>();

  constructor(
    private readonly protocol: Protocol,
    private readonly port: number,
  ) {
    this.prefix = snakeCase(protocol.name);
    for (const reserved of ['opcode', 'packet', 'direction', 'expert']) {
      this.used.add(`${this.prefix}.${reserved}`);
    }
  }

  file(): string {
    const { protocol, prefix } = this;
    const enums = protocol.enums.map((e) => {
      // A value listed twice keeps its first name, which is also what a value table can hold.
      const seen = new Set<number>();
      const names = e.values
        .filter((v) => !seen.has(v.value) && seen.add(v.value))
        .map((v) => `[${v.value}] = ${luaString(v.name)}`);
      return `ENUMS[${luaString(e.name)}] = { ${names.join(', ')} }`;
    });
    const structs = protocol.structs.map((s) => {
      const base = `${prefix}.${snakeCase(s.name)}`;
      return `STRUCTS[${luaString(s.name)}] = ${this.fieldList(s.fields, base)}`;
    });
    const packets = protocol.packets.map((p) => this.packetEntry(p));
    const opcodeDigits = protocol.opcode === 'u8' ? 2 : 4;
    const opcodeField = FIELD_CONSTRUCTORS[protocol.opcode];

    return `-- Generated by pktspec from ${protocol.name}. Do not edit.
--
-- Wireshark dissector for the ${protocol.name} protocol. Copy it to the personal plugins
-- folder (Help > About Wireshark > Folders) and restart Wireshark, or load it once with
-- tshark -X lua_script:${protocol.name}.lua. Needs Wireshark 3.6 or later.
--
-- A message is the opcode followed by the packet body, with no length prefix, so each UDP
-- datagram or TCP segment is read as one message. Set the TCP or UDP port in
-- Edit > Preferences > Protocols > ${protocol.name}, or use Analyze > Decode As.
-- Direction comes from the server port: traffic to it is client to server, traffic from it
-- is server to client. Without a known server port the opcode is tried in both directions.

local proto = Proto(${luaString(prefix)}, ${luaString(protocol.name)})

local LITTLE = ${protocol.endian === 'little'}
local OPCODE_SIZE = ${PRIMITIVE_SIZES[protocol.opcode]}
local OPCODE_FORMAT = "0x%0${opcodeDigits}X"
local DEFAULT_PORT = ${this.port}
local MAX_DEPTH = 64
local MAX_EMPTY_ELEMENTS = 65535

local fields = {}
local function reg(field)
  fields[#fields + 1] = field
  return field
end

local ef_truncated = ProtoExpert.new(${luaString(`${prefix}.expert.truncated`)}, "Truncated packet", expert.group.MALFORMED, expert.severity.ERROR)
local ef_opcode = ProtoExpert.new(${luaString(`${prefix}.expert.unknown_opcode`)}, "Unknown opcode", expert.group.UNDECODED, expert.severity.WARN)
local ef_enum = ProtoExpert.new(${luaString(`${prefix}.expert.bad_enum`)}, "Unknown enum value", expert.group.MALFORMED, expert.severity.WARN)
local ef_length = ProtoExpert.new(${luaString(`${prefix}.expert.bad_length`)}, "Length past the end of the packet", expert.group.MALFORMED, expert.severity.ERROR)
local ef_depth = ProtoExpert.new(${luaString(`${prefix}.expert.too_deep`)}, "Nesting too deep", expert.group.MALFORMED, expert.severity.ERROR)
local ef_trailing = ProtoExpert.new(${luaString(`${prefix}.expert.trailing`)}, "Data after the packet", expert.group.UNDECODED, expert.severity.NOTE)
local ef_direction = ProtoExpert.new(${luaString(`${prefix}.expert.direction`)}, "Direction not known", expert.group.ASSUMPTION, expert.severity.NOTE)
proto.experts = { ef_truncated, ef_opcode, ef_enum, ef_length, ef_depth, ef_trailing, ef_direction }

local f_opcode = reg(ProtoField.${opcodeField}(${luaString(`${prefix}.opcode`)}, "Opcode", base.HEX))
local f_packet = reg(ProtoField.string(${luaString(`${prefix}.packet`)}, "Packet"))
local f_direction = reg(ProtoField.string(${luaString(`${prefix}.direction`)}, "Direction"))

local ENUMS = {}
${enums.join('\n')}

local STRUCTS = {}
${structs.join('\n\n')}

local PACKETS = { c2s = {}, s2c = {} }
${packets.join('\n\n')}

proto.fields = fields

proto.prefs.tcp_port = Pref.uint("TCP port", DEFAULT_PORT, "TCP port carrying the protocol, 0 for none")
proto.prefs.udp_port = Pref.uint("UDP port", DEFAULT_PORT, "UDP port carrying the protocol, 0 for none")
proto.prefs.server_port = Pref.uint("Server port", DEFAULT_PORT, "Port the server listens on, used to tell the direction; 0 uses the TCP and UDP ports")

${RUNTIME}`;
  }

  private packetEntry(packet: Packet): string {
    const base = `${this.prefix}.${snakeCase(packet.name)}`;
    const opcode = hex(packet.opcode, this.protocol.opcode === 'u8' ? 2 : 4);
    return `PACKETS.${packet.direction}[${opcode}] = { name = ${luaString(packet.name)}, fields = ${this.fieldList(packet.fields, base)} }`;
  }

  private fieldList(fields: Field[], base: string): string {
    if (fields.length === 0) return '{}';
    return `{\n${fields.map((f) => `  ${this.fieldEntry(f, base)},`).join('\n')}\n}`;
  }

  private fieldEntry(field: Field, base: string): string {
    const abbrev = uniqueName(`${base}.${snakeCase(field.name)}`, this.used);
    const name = luaString(field.name);
    const { type } = field;
    if (type.kind !== 'array' && type.kind !== 'fixedArray') {
      return `{ pf = reg(${this.protoField(type, abbrev, name)}), t = ${this.descriptor(type)} }`;
    }
    const item = uniqueName(`${abbrev}.item`, this.used);
    const container =
      type.kind === 'array'
        ? `ProtoField.${LENGTH_CONSTRUCTORS[PRIMITIVE_SIZES[type.length] as 1 | 2 | 4]}(${luaString(abbrev)}, ${name}, base.DEC)`
        : `ProtoField.none(${luaString(abbrev)}, ${name})`;
    const shape =
      type.kind === 'array'
        ? `count = ${PRIMITIVE_SIZES[type.length]}, min = ${wireSize(type.element, this.protocol).min}`
        : `size = ${type.size}`;
    return `{ name = ${name}, pf = reg(${container}), item = reg(${this.protoField(type.element, item, name)}), t = ${this.descriptor(type.element)}, ${shape} }`;
  }

  private protoField(type: ElementType, abbrev: string, name: string): string {
    const head = `${luaString(abbrev)}, ${name}`;
    switch (type.kind) {
      case 'primitive':
        return type.name === 'bool' || type.name === 'f32' || type.name === 'f64'
          ? `ProtoField.${FIELD_CONSTRUCTORS[type.name]}(${head})`
          : `ProtoField.${FIELD_CONSTRUCTORS[type.name]}(${head}, base.DEC)`;
      case 'string':
        return `ProtoField.string(${head})`;
      case 'bytes':
      case 'fixedBytes':
        return `ProtoField.bytes(${head})`;
      case 'struct':
        return `ProtoField.none(${head})`;
      case 'enum': {
        const base = findEnum(this.protocol, type.name).type;
        return `ProtoField.${FIELD_CONSTRUCTORS[base]}(${head}, base.DEC, ENUMS[${luaString(type.name)}])`;
      }
    }
  }

  private descriptor(type: ElementType): string {
    switch (type.kind) {
      case 'primitive':
        return `{ k = "num", size = ${PRIMITIVE_SIZES[type.name]} }`;
      case 'string':
        return `{ k = "string", len = ${PRIMITIVE_SIZES[type.length]} }`;
      case 'bytes':
        return `{ k = "bytes", len = ${PRIMITIVE_SIZES[type.length]} }`;
      case 'fixedBytes':
        return `{ k = "fixed", size = ${type.size} }`;
      case 'struct':
        return `{ k = "struct", s = ${luaString(type.name)} }`;
      case 'enum': {
        const base = findEnum(this.protocol, type.name).type;
        return `{ k = "enum", e = ${luaString(type.name)}, size = ${PRIMITIVE_SIZES[base]}, signed = ${base.startsWith('i')} }`;
      }
    }
  }
}

function snakeCase(name: string): string {
  return name
    .replace(/([a-z0-9])([A-Z])/g, '$1_$2')
    .replace(/-/g, '_')
    .toLowerCase();
}

/** Quotes text for Lua; anything outside printable ASCII becomes decimal byte escapes. */
function luaString(value: string): string {
  let out = '"';
  for (const char of value) {
    if (char === '\\' || char === '"') {
      out += '\\' + char;
    } else if (char >= ' ' && char <= '~') {
      out += char;
    } else {
      for (const byte of Buffer.from(char, 'utf8')) out += '\\' + String(byte).padStart(3, '0');
    }
  }
  return out + '"';
}

const RUNTIME = `local ABORT = {}

-- Stands in for the tree while trying a direction, so a wrong guess shows nothing.
local sink = { problems = 0 }
setmetatable(sink, {
  __index = function(_, key)
    if key == "add_proto_expert_info" then
      return function(self)
        self.problems = self.problems + 1
        return self
      end
    end
    return function(self)
      return self
    end
  end,
})

local function fail(tree, expert, message)
  tree:add_proto_expert_info(expert, message)
  error(ABORT, 0)
end

local function need(tree, tvb, off, size)
  local left = tvb:len() - off
  if size > left then
    fail(tree, ef_truncated, string.format("Truncated: %d more bytes needed at offset %d, %d left", size, off, left))
  end
end

local function read_unsigned(tvb, off, size)
  if LITTLE and size > 1 then
    return tvb(off, size):le_uint()
  end
  return tvb(off, size):uint()
end

local function read_signed(tvb, off, size)
  if LITTLE and size > 1 then
    return tvb(off, size):le_int()
  end
  return tvb(off, size):int()
end

local function add_number(tree, field, range)
  if LITTLE then
    return tree:add_le(field, range)
  end
  return tree:add(field, range)
end

local dissect_fields

local function dissect_value(field, t, tvb, off, tree, depth, label)
  local kind = t.k
  if kind == "num" then
    need(tree, tvb, off, t.size)
    add_number(tree, field, tvb(off, t.size))
    return off + t.size
  elseif kind == "enum" then
    need(tree, tvb, off, t.size)
    local value
    if t.signed then
      value = read_signed(tvb, off, t.size)
    else
      value = read_unsigned(tvb, off, t.size)
    end
    local item = add_number(tree, field, tvb(off, t.size))
    if ENUMS[t.e][value] == nil then
      item:add_proto_expert_info(ef_enum, string.format("Unknown %s value: %d", t.e, value))
    end
    return off + t.size
  elseif kind == "string" or kind == "bytes" then
    need(tree, tvb, off, t.len)
    local length = read_unsigned(tvb, off, t.len)
    local start = off + t.len
    local left = tvb:len() - start
    if length > left then
      fail(tree, ef_length, string.format("Length %d runs past the end of the packet, %d bytes left", length, left))
    end
    if kind == "string" then
      tree:add_packet_field(field, tvb(start, length), ENC_UTF_8)
    else
      tree:add(field, tvb(start, length))
    end
    return start + length
  elseif kind == "fixed" then
    need(tree, tvb, off, t.size)
    tree:add(field, tvb(off, t.size))
    return off + t.size
  end
  if depth >= MAX_DEPTH then
    fail(tree, ef_depth, "Structs are nested more than " .. MAX_DEPTH .. " levels deep")
  end
  local item = tree:add(field, tvb(off, 0))
  if label then
    item:set_text(label)
  end
  local last = dissect_fields(STRUCTS[t.s], tvb, off, item, depth + 1)
  item:set_len(last - off)
  return last
end

local function dissect_field(field, tvb, off, tree, depth)
  if not field.count and not field.size then
    return dissect_value(field.pf, field.t, tvb, off, tree, depth)
  end
  local start = off
  local n, item
  if field.count then
    need(tree, tvb, off, field.count)
    n = read_unsigned(tvb, off, field.count)
    item = add_number(tree, field.pf, tvb(off, field.count))
    off = off + field.count
    -- Elements that take no bytes cannot be bounded by the data, so they get a fixed cap.
    local left = tvb:len() - off
    local limit = MAX_EMPTY_ELEMENTS
    if field.min > 0 then
      limit = math.floor(left / field.min)
    end
    if n > limit then
      fail(item, ef_length, string.format("Count %d needs at least %d bytes, %d left", n, n * field.min, left))
    end
  else
    n = field.size
    item = tree:add(field.pf, tvb(off, 0))
    item:append_text(string.format(" [%d]", n))
  end
  for i = 0, n - 1 do
    off = dissect_value(field.item, field.t, tvb, off, item, depth, string.format("%s[%d]", field.name, i))
  end
  item:set_len(off - start)
  return off
end

function dissect_fields(list, tvb, off, tree, depth)
  for _, field in ipairs(list) do
    off = dissect_field(field, tvb, off, tree, depth)
  end
  return off
end

-- Lower is better: problems found, plus one for left-over bytes, plus a lot for giving up.
local function probe(entry, tvb)
  sink.problems = 0
  local ok, last = pcall(dissect_fields, entry.fields, tvb, OPCODE_SIZE, sink, 0)
  if not ok then
    if last ~= ABORT then
      error(last, 0)
    end
    return sink.problems + 1000
  end
  if last < tvb:len() then
    return sink.problems + 1
  end
  return sink.problems
end

local function directions(pinfo)
  local ports = {}
  if proto.prefs.server_port ~= 0 then
    ports[proto.prefs.server_port] = true
  else
    ports[proto.prefs.tcp_port] = true
    ports[proto.prefs.udp_port] = true
  end
  ports[0] = nil
  local from, to = ports[pinfo.src_port], ports[pinfo.dst_port]
  if to and not from then
    return { "c2s" }
  elseif from and not to then
    return { "s2c" }
  end
  return { "c2s", "s2c" }
end

local function dissect_message(tvb, pinfo, root)
  pinfo.cols.info = "Truncated packet"
  need(root, tvb, 0, OPCODE_SIZE)
  local opcode = read_unsigned(tvb, 0, OPCODE_SIZE)
  add_number(root, f_opcode, tvb(0, OPCODE_SIZE))

  local matches = {}
  for _, direction in ipairs(directions(pinfo)) do
    local entry = PACKETS[direction][opcode]
    if entry then
      matches[#matches + 1] = { direction = direction, entry = entry }
    end
  end
  if #matches == 0 then
    local text = string.format("Unknown opcode " .. OPCODE_FORMAT, opcode)
    pinfo.cols.info = text
    root:append_text(": " .. text)
    root:add_proto_expert_info(ef_opcode, text)
    return
  end

  local chosen = matches[1]
  local tied = false
  if #matches > 1 then
    local best = probe(chosen.entry, tvb)
    for i = 2, #matches do
      local score = probe(matches[i].entry, tvb)
      if score < best then
        chosen, best, tied = matches[i], score, false
      elseif score == best then
        tied = true
      end
    end
  end

  local name = chosen.entry.name
  pinfo.cols.info = name
  root:append_text(": " .. name)
  root:add(f_packet, tvb(0, OPCODE_SIZE), name):set_generated()
  root:add(f_direction, tvb(0, 0), chosen.direction):set_generated()
  if tied then
    root:add_proto_expert_info(ef_direction, "The opcode fits both directions, assuming " .. chosen.direction .. "; set the server port preference")
  end

  local last = dissect_fields(chosen.entry.fields, tvb, OPCODE_SIZE, root, 0)
  if last < tvb:len() then
    root:add_proto_expert_info(ef_trailing, string.format("%d bytes follow the packet", tvb:len() - last))
  end
end

function proto.dissector(tvb, pinfo, tree)
  if tvb:len() == 0 then
    return 0
  end
  pinfo.cols.protocol = proto.description
  local root = tree:add(proto, tvb())
  local ok, err = pcall(dissect_message, tvb, pinfo, root)
  if not ok and err ~= ABORT then
    error(err, 0)
  end
  return tvb:len()
end

local registered = { tcp = 0, udp = 0 }

local function register(name, key, port)
  if registered[key] == port then
    return
  end
  local dissectors = DissectorTable.get(name)
  if registered[key] ~= 0 then
    dissectors:remove(registered[key], proto)
  end
  if port ~= 0 then
    dissectors:add(port, proto)
  end
  registered[key] = port
end

local function register_ports()
  register("tcp.port", "tcp", proto.prefs.tcp_port)
  register("udp.port", "udp", proto.prefs.udp_port)
end

proto.prefs_changed = register_ports
register_ports()

-- Offered in Analyze > Decode As even while no port is set.
DissectorTable.get("tcp.port"):add_for_decode_as(proto)
DissectorTable.get("udp.port"):add_for_decode_as(proto)
`;
